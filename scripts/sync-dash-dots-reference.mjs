#!/usr/bin/env node
// Regenerates skills/dash-dots/references/{components,dash-api,pages-and-dot}.md
// from the Dash Dots reference pages in Monime's docs source.
//
//   node scripts/sync-dash-dots-reference.mjs <path-to-docs-source>
//
// The docs pages are themselves generated from the Dot source, so this only
// folds them into one file per topic and turns MDX into plain Markdown.

import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const DOCS_URL = 'https://docs2.monime.io';
const REFERENCE = 'content/docs/products/dash-dots/reference';
const OUT = join(dirname(fileURLToPath(import.meta.url)), '../skills/dash-dots/references');

const docsRoot = process.argv[2];
if (!docsRoot) {
  console.error('Usage: node scripts/sync-dash-dots-reference.mjs <path-to-docs-source>');
  process.exit(1);
}
const ref = join(docsRoot, REFERENCE);

const pageList = (dir) =>
  JSON.parse(readFileSync(join(ref, dir, 'meta.json'), 'utf8')).pages.filter((p) => !p.startsWith('---'));

function parse(file) {
  const raw = readFileSync(file, 'utf8');
  const match = raw.match(/^---\n([\s\S]*?)\n---\n/);
  const front = Object.fromEntries(
    match[1].split('\n').map((line) => {
      const i = line.indexOf(':');
      return [line.slice(0, i).trim(), line.slice(i + 1).trim().replace(/^"(.*)"$/, '$1')];
    }),
  );
  const version = raw.match(/from Dot ([\w.-]+)\./)?.[1];
  return { ...front, version, body: raw.slice(match[0].length) };
}

// Point a docs link at a heading in one of our files when we carry it, else at the docs site.
function rewriteLinks(text, local) {
  return text.replace(/\]\((\/docs\/[^)\s]+)\)/g, (_, href) => {
    const [path, hash] = href.split('#');
    const target = local(path, hash);
    return `](${target ?? DOCS_URL + href})`;
  });
}

function toMarkdown(body, { demote, local }) {
  const out = [];
  let inCode = false;
  let icons = null;
  for (let line of body.split('\n')) {
    if (line.startsWith('```')) {
      inCode = !inCode;
      out.push(inCode ? line.replace(/^```(\w+)\s+wrap\b/, '```$1') : line);
      continue;
    }
    if (inCode) {
      out.push(line);
      continue;
    }
    if (/^\{\/\*.*\*\/\}$/.test(line.trim())) continue;
    if (/^<Screenshot\b/.test(line.trim())) continue;
    if (/^<div style=\{\{ display: 'grid'/.test(line)) {
      icons = [];
      continue;
    }
    if (icons) {
      if (line.trim() === '</div>') {
        out.push(icons.map((n) => `\`${n}\``).join(' '));
        icons = null;
      } else {
        const name = line.match(/<code>([^<]+)<\/code>/)?.[1];
        if (name) icons.push(name);
      }
      continue;
    }
    const callout = line.match(/^<(Note|Info|Tip|Warning)(?: title="([^"]*)")?>(.*)$/);
    if (callout) {
      const [, , title, rest] = callout;
      line = `> ${title ? `**${title}.** ` : ''}${rest.replace(/<\/(Note|Info|Tip|Warning)>$/, '')}`;
    } else if (/^<\/(Note|Info|Tip|Warning)>$/.test(line.trim())) {
      continue;
    }
    if (line.startsWith('#')) line = '#'.repeat(demote) + line;
    out.push(rewriteLinks(line, local));
  }
  return out.join('\n').replace(/\n{3,}/g, '\n\n').trim();
}

const slug = (heading) =>
  heading.toLowerCase().replace(/[`]/g, '').replace(/[^\w\s-]/g, '').trim().replace(/\s+/g, '-');

function header(title, intro, version) {
  return [
    `# ${title}`,
    '',
    `<!-- Generated by scripts/sync-dash-dots-reference.mjs from the Dash Dots docs (Dot ${version}). Don't edit by hand. -->`,
    '',
    intro,
    '',
  ].join('\n');
}

// Components: one section per component, in the docs' order.
{
  const index = parse(join(ref, 'components/index.mdx'));
  const names = Object.fromEntries(
    pageList('components').map((p) => [p, parse(join(ref, 'components', `${p}.mdx`)).title]),
  );
  const local = (path, hash) => {
    const m = path.match(/^\/docs\/products\/dash-dots\/reference\/components(?:\/([\w-]+))?$/);
    if (!m) return null;
    if (!m[1]) return hash ? `#${hash}` : '#';
    return names[m[1]] ? `#${slug(names[m[1]])}` : null;
  };
  const parts = [
    header(
      'Components',
      `Every component a \`view.dml\` can use, with its props, events and children. Source: ${DOCS_URL}/docs/products/dash-dots/reference/components`,
      index.version,
    ),
    toMarkdown(index.body, { demote: 0, local }),
  ];
  for (const page of pageList('components')) {
    const doc = parse(join(ref, 'components', `${page}.mdx`));
    parts.push(`## ${doc.title}\n\n${doc.description}\n\n${toMarkdown(doc.body, { demote: 1, local })}`);
  }
  writeFileSync(join(OUT, 'components.md'), parts.join('\n\n') + '\n');
}

// Dash API: the index, then each group.
{
  const index = parse(join(ref, 'dash-api/index.mdx'));
  const local = (path, hash) => {
    if (/^\/docs\/products\/dash-dots\/reference\/dash-api(\/[\w-]+)?$/.test(path)) {
      return hash ? `#${hash}` : '#dash-api';
    }
    return null;
  };
  const parts = [
    header(
      'Dash API',
      `Every \`this.dash\` call, its types and the helpers in \`@monimesl/dot-runtime\`. Source: ${DOCS_URL}/docs/products/dash-dots/reference/dash-api`,
      index.version,
    ),
    toMarkdown(index.body, { demote: 0, local }),
  ];
  for (const page of pageList('dash-api')) {
    const doc = parse(join(ref, 'dash-api', `${page}.mdx`));
    parts.push(`## ${doc.title}\n\n${doc.description}\n\n${toMarkdown(doc.body, { demote: 1, local })}`);
  }
  writeFileSync(join(OUT, 'dash-api.md'), parts.join('\n\n') + '\n');
}

// definePage, defineDot, the theme, events and testPage.
{
  const doc = parse(join(ref, 'pages-and-dot.mdx'));
  const dotJson = parse(join(ref, 'dot-json.mdx'));
  const local = (path, hash) =>
    path === '/docs/products/dash-dots/reference/pages-and-dot' && hash ? `#${hash}` : null;
  writeFileSync(
    join(OUT, 'pages-and-dot.md'),
    [
      header(
        'Pages, dot.ts and dot.json',
        `The types behind \`definePage\`, \`defineDot\`, \`this\` in controllers, events and \`testPage\`, then every \`dot.json\` field. Source: ${DOCS_URL}/docs/products/dash-dots/reference/pages-and-dot`,
        doc.version,
      ),
      toMarkdown(doc.body, { demote: 0, local }),
      `## dot.json\n\n${toMarkdown(dotJson.body, { demote: 1, local: () => null })}`,
    ].join('\n\n') + '\n',
  );
}

console.log(`Wrote components.md, dash-api.md and pages-and-dot.md to ${OUT}`);
